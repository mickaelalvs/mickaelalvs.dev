// Builds CSS-mask icon stylesheets from Iconify sets, keeping only the icons listed below.
// Runs before `dev` and `build`. The outputs are git-ignored.
//
//   <i className="ri-github-line" />  ->  app/icons.css (UI and social icons, loaded everywhere)
//   <i className="si-react" />        ->  modules/articles/components/code-icons.css
//                                         (tech logos, imported by CodeBlock so only articles load it)
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {getIconsCSS} from '@iconify/utils';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const GROUPS = [
  {
    prefix: 'ri',
    pkg: '@iconify-json/ri',
    out: 'app/icons.css',
    icons: [
      'arrow-right-up-line',
      'bluesky-line',
      'check-line',
      'close-line',
      'command-line',
      'external-link-line',
      'file-copy-line',
      'github-line',
      'linkedin-line',
      'mail-line',
      'moon-line',
      'sun-line',
      'twitter-x-line',
    ],
  },
  {
    prefix: 'si',
    pkg: '@iconify-json/simple-icons',
    out: 'modules/articles/components/code-icons.css',
    icons: ['css3', 'gnubash', 'html5', 'javascript', 'json', 'markdown', 'react', 'svelte', 'typescript', 'vuedotjs'],
  },
];

for (const {prefix, pkg, out, icons} of GROUPS) {
  const iconSet = JSON.parse(readFileSync(require.resolve(`${pkg}/icons.json`), 'utf8'));

  const perIconRules = getIconsCSS(iconSet, icons, {
    iconSelector: `.${prefix}-{name}`,
    format: 'expanded',
    mode: 'mask',
    varName: null,
  })
    // Drop Iconify's shared block (plain-class specificity would beat component styles such as
    // `display: none` on the inactive theme icon); it is re-emitted below inside `:where()`.
    .replace(/^[^{}\n]*,[^{}\n]*\{[^}]*\}\n/m, '')
    // Targets are evergreen (see browserslist): the unprefixed `mask-*` properties are enough.
    .replace(/^\s*-webkit-mask[^\n]*\n/gm, '')
    .trim();

  const css = `/* Generated by scripts/generate-icons.mjs from Iconify sets. Do not edit by hand. */
/* :where() keeps specificity at 0, so component styles always win. */
:where([class^='${prefix}-'], [class*=' ${prefix}-']) {
  display: inline-block;
  width: 1em;
  height: 1em;
  vertical-align: -0.125em;
  background-color: currentColor;
  mask-repeat: no-repeat;
  mask-size: 100% 100%;
}

${perIconRules}
`;

  mkdirSync(dirname(join(root, out)), {recursive: true});
  writeFileSync(join(root, out), css);
  console.log(`${out}: ${icons.length} icons, ${(css.length / 1024).toFixed(1)}KB`);
}
